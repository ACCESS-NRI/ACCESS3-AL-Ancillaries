# Soil ancillary variable for each of the 2D gridinfo soil variables
SOIL_SOURCES = {
    'bch': 'b',
    'ssat': 'sm_sat',
    'sfc': 'sm_crit',
    'swilt': 'sm_wilt',
    'sucs': 'sathh',
    'hyds': 'satcon',
    'rhosoil': 'BD',
    'css': 'hcap',
    'cnsd': 'hcon',
    'sand': 'T_SAND',
    'silt': 'T_SILT',
    'clay': 'T_CLAY',
    'albedo2': 'soil_albedo',
}

# Variables the workflow does not generate, which can only come from a
# reference gridinfo
REFERENCE_VARIABLES = ['Ndep', 'Nfix', 'Pdust', 'Pwea', 'SoilOrder', 'isoil']


def _parse_args():
    parser = argparse.ArgumentParser(description=__doc__)

    parser.add_argument(
            '--soil',
            required=True,
            type=str,
            help='Soil parameters ancillary (NetCDF), from merge_soils.'
            )

    parser.add_argument(
            '--vegetation-fraction',
            required=True,
            type=str,
            help='Land cover tile fractions (NetCDF).'
            )

    parser.add_argument(
            '--lai',
            required=True,
            type=str,
            help='Total LAI monthly climatology (NetCDF), from regrid_LAI.'
            )

    parser.add_argument(
            '--land-mask',
            required=True,
            type=str,
            help='Land sea mask (NetCDF), which also defines the grid.'
            )

    parser.add_argument(
            '--soil-initial-conditions',
            required=True,
            type=str,
            help="""Soil initial conditions (NetCDF), from
            functional_soil_initial_conditions."""
            )

    parser.add_argument(
            '--reference-gridinfo',
            required=False,
            type=str,
            default='',
            help="""Gridinfo file to sample the variables the workflow does
            not generate from. Leave empty to omit them."""
            )

    parser.add_argument(
            '--output',
            required=True,
            type=str,
            help='Path to write the gridinfo file to.'
            )

    return parser.parse_args()


def load_var(path, var_name):
    """Load the cube with the given variable name from a NetCDF file."""
    return iris.load_cube(path, iris.NameConstraint(var_name=var_name))


def load_vars(path, var_names):
    """
    Load the cubes with the given variable names from a NetCDF file, reading
    the file only once. Returns a dictionary of cubes keyed by variable name.
    """
    cubes = iris.load(path, [iris.NameConstraint(var_name=var_name)
                             for var_name in var_names])
    return {var_name: cubes.extract_cube(iris.NameConstraint(var_name=var_name))
            for var_name in var_names}


def as_float(cube):
    """Cube data as a float64 array, with masked points set to NaN."""
    return numpy.ma.filled(
            numpy.ma.asarray(cube.data, dtype=numpy.float64),
            numpy.nan
            )


def load_grid(land_mask_path):
    """
    Load the land sea mask, returning the latitude and longitude points, the
    boolean land mask and the area of every grid cell in m^2.
    """
    land_mask = load_var(land_mask_path, 'land_binary_mask')
    is_land = numpy.ma.filled(land_mask.data, 0).astype(bool)

    for coord_name in ('latitude', 'longitude'):
        if not land_mask.coord(coord_name).has_bounds():
            land_mask.coord(coord_name).guess_bounds()
    area = iris.analysis.cartography.area_weights(land_mask, normalize=False)

    latitude = land_mask.coord('latitude').points
    longitude = land_mask.coord('longitude').points

    return latitude, longitude, is_land, area


def soil_fields(soil_path):
    """
    Read the soil parameters, converted to the gridinfo units. Returns a
    dictionary of 2D (latitude, longitude) arrays keyed by gridinfo name.
    """
    cubes = load_vars(soil_path, SOIL_SOURCES.values())
    fields = {name: as_float(cubes[source])
              for name, source in SOIL_SOURCES.items()}

    # kg m-2 s-1 of water to m s-1
    fields['hyds'] = fields['hyds'] / WATER_DENSITY

    # Volumetric (J m-3 K-1) to specific (J kg-1 K-1) heat capacity, which is
    # undefined where there is no bulk density
    with numpy.errstate(divide='ignore', invalid='ignore'):
        fields['css'] = numpy.where(
                fields['rhosoil'] > 0.0,
                fields['css'] / fields['rhosoil'],
                numpy.nan
                )

    # CABLE takes one snow-free bare soil albedo per radiation band, which we
    # don't have, so use the single soil albedo for each band
    fields['Albedo'] = numpy.repeat(
            fields['albedo2'][numpy.newaxis],
            NUM_RAD_BANDS,
            axis=0
            )

    return fields


def compress_tiles(fractions, tile_ids):
    """
    Compress the full set of tile fractions (tile, latitude, longitude) to
    only the tiles with non-zero fraction in each cell, ordered by descending
    fraction. The patch dimension is the largest number of non-zero tiles in
    any cell.

    Returns the tile ID (iveg) and fraction (patchfrac) of each patch, with
    unused patches set to NaN.
    """
    fractions = numpy.nan_to_num(fractions, nan=0.0)
    num_patches = max(int((fractions > 0.0).sum(axis=0).max()), 1)

    order = numpy.argsort(-fractions, axis=0, kind='stable')[:num_patches]
    patchfrac = numpy.take_along_axis(fractions, order, axis=0)
    iveg = tile_ids[order].astype(numpy.float64)

    unused = patchfrac <= 0.0
    patchfrac[unused] = numpy.nan
    iveg[unused] = numpy.nan

    return iveg, patchfrac


def vegetation_fields(vegetation_fraction_path, is_land):
    """Read the land cover fractions and convert to iveg and patchfrac."""
    tiles = load_var(vegetation_fraction_path, 'vegetation_area_fraction')
    tile_ids = tiles.coord('pseudo_level').points

    fractions = numpy.where(is_land, as_float(tiles), 0.0)
    iveg, patchfrac = compress_tiles(fractions, tile_ids)

    return {'iveg': iveg, 'patchfrac': patchfrac}


def lai_fields(lai_path):
    """Read the monthly total LAI."""
    lai = as_float(load_var(lai_path, 'leaf_area_index'))

    if lai.shape[0] != NUM_MONTHS:
        raise ValueError(f'Expected {NUM_MONTHS} months of LAI, found '
                         f'{lai.shape[0]}.')

    return {'LAI': lai}


def soil_state_fields(initial_conditions_path, is_land):
    """
    Read the soil moisture and temperature initial conditions and repeat them
    for every month. The snow depth is zero everywhere.
    """
    fields = {}
    sources = {
        'SoilMoist': 'volumetric_soil_moisture_content_in_a_layer',
        'SoilTemp': 'soil_temperature',
    }
    cubes = load_vars(initial_conditions_path, sources.values())
    for name, source in sources.items():
        cube = cubes[source]

        # Move the depth to the front, so we have (soil, latitude, longitude)
        depth_dim = cube.coord_dims('depth')[0]
        values = numpy.moveaxis(as_float(cube), depth_dim, 0)

        if values.shape[0] != NUM_SOIL_LAYERS:
            raise ValueError(f'CABLE requires {NUM_SOIL_LAYERS} soil layers, '
                             f'but {source} has {values.shape[0]}.')

        fields[name] = numpy.repeat(values[numpy.newaxis], NUM_MONTHS, axis=0)

    fields['SnowDepth'] = numpy.zeros((NUM_MONTHS, *is_land.shape))

    return fields


def lat_lon_to_xyz(latitude, longitude):
    """Convert latitude and longitude in degrees to points on a unit sphere."""
    lat = numpy.deg2rad(latitude)
    lon = numpy.deg2rad(longitude)
    return numpy.stack([numpy.cos(lat) * numpy.cos(lon),
                        numpy.cos(lat) * numpy.sin(lon),
                        numpy.sin(lat)], axis=-1)


def reference_fields(reference_path, latitude, longitude):
    """
    Sample the variables the workflow does not generate from a reference
    gridinfo, using the nearest valid (non-missing) reference point.
    """
    fields = {}
    target_lat, target_lon = numpy.meshgrid(latitude, longitude, indexing='ij')
    target_points = lat_lon_to_xyz(target_lat, target_lon)

    with netCDF4.Dataset(reference_path) as reference:
        ref_lat, ref_lon = numpy.meshgrid(
                reference['latitude'][:],
                reference['longitude'][:],
                indexing='ij'
                )
        ref_points = lat_lon_to_xyz(ref_lat, ref_lon)

        for name in REFERENCE_VARIABLES:
            if name not in reference.variables:
                print(f'{name}: not found in the reference gridinfo '
                      f'{reference_path}, omitted.')
                continue

            values = numpy.ma.filled(
                    numpy.ma.asarray(reference[name][:], dtype=numpy.float64),
                    numpy.nan
                    )
            valid = numpy.isfinite(values)

            tree = scipy.spatial.cKDTree(ref_points[valid])
            _, nearest = tree.query(target_points.reshape(-1, 3))
            fields[name] = values[valid][nearest].reshape(target_lat.shape)

            print(f'{name}: sourced from the reference gridinfo '
                  f'{reference_path}.')

    return fields


def write_gridinfo(output_path, latitude, longitude, is_land, fields, history):
    """
    Write the gridinfo fields to NetCDF, in the order and with the structure
    given by GRIDINFO_SPEC. NaN and non-land points are written as the fill
    value.
    """
    with netCDF4.Dataset(output_path, 'w', format='NETCDF4') as gridinfo:
        gridinfo.title = 'CABLE gridinfo generated by ACCESS3-AL-Ancillaries'
        gridinfo.history = history

        # Create the dimensions of the fields we have
        sizes = {
            'rad': NUM_RAD_BANDS,
            'latitude': len(latitude),
            'longitude': len(longitude),
            'time': NUM_MONTHS,
            'soil': NUM_SOIL_LAYERS,
            'patch': fields['iveg'].shape[0],
        }
        used_dims = {dim for name in fields for dim in GRIDINFO_SPEC[name][0]}
        for dim, size in sizes.items():
            if dim in used_dims or dim in ('latitude', 'longitude'):
                gridinfo.createDimension(dim, size)

        for coord_name, points, units in (
                ('latitude', latitude, 'degrees_north'),
                ('longitude', longitude, 'degrees_east')
                ):
            coord = gridinfo.createVariable(coord_name, 'f4', (coord_name,))
            coord[:] = points
            coord.long_name = coord_name
            coord.units = units
            coord.min = numpy.float32(points.min())
            coord.max = numpy.float32(points.max())

        for name, (dims, fill_value, attributes) in GRIDINFO_SPEC.items():
            if name not in fields:
                continue

            variable = gridinfo.createVariable(
                    name,
                    fill_value.dtype,
                    (*dims, 'latitude', 'longitude'),
                    fill_value=fill_value,
                    zlib=True
                    )
            variable.missing_value = fill_value
            for key, value in attributes.items():
                variable.setncattr(key, value)

            values = fields[name]
            invalid = ~(is_land & numpy.isfinite(values))
            values = numpy.where(invalid, fill_value, values)
            if numpy.issubdtype(fill_value.dtype, numpy.integer):
                values = numpy.rint(values)

            variable[:] = numpy.ma.masked_array(
                    values.astype(fill_value.dtype),
                    mask=invalid
                    )


def main(soil_path,
         vegetation_fraction_path,
         lai_path,
         land_mask_path,
         initial_conditions_path,
         reference_path,
         output_path,
         history
         ):
    latitude, longitude, is_land, area = load_grid(land_mask_path)

    fields = {'area': area}
    fields.update(soil_fields(soil_path))
    fields.update(vegetation_fields(vegetation_fraction_path, is_land))
    fields.update(lai_fields(lai_path))
    fields.update(soil_state_fields(initial_conditions_path, is_land))

    if reference_path:
        fields.update(reference_fields(reference_path, latitude, longitude))
    else:
        print(f'No reference gridinfo given, omitting '
              f'{", ".join(REFERENCE_VARIABLES)}.')

    write_gridinfo(output_path, latitude, longitude, is_land, fields, history)


if __name__ == '__main__':
    args = _parse_args()

    main(
            args.soil,
            args.vegetation_fraction,
            args.lai,
            args.land_mask,
            args.soil_initial_conditions,
            args.reference_gridinfo,
            args.output,
            ' '.join(sys.argv)
            )
