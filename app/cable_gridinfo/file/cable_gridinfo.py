#!/usr/bin/env python
"""
Combine the ancillaries generated by the workflow into a CABLE gridinfo file.

The structure of the output (variable names, dimensions, data types, units and
fill values) follows the CABLE gridinfo convention, e.g.
gridinfo_CSIRO_CRU05x05_4tiles.nc, but the grid is that of the workflow land
sea mask. Every variable is set to its fill value away from land points.
"""

import argparse
import sys

import iris
import iris.analysis.cartography
import netCDF4
import numpy
import scipy.spatial

iris.FUTURE.datum_support = True

WATER_DENSITY = 1000.0  # kg m-3
NUM_MONTHS = 12
NUM_RAD_BANDS = 3
NUM_SOIL_LAYERS = 6

FLOAT_FILL = numpy.float32(-1.0)
NUTRIENT_FILL = numpy.float32(-99.0)
INT_FILL = numpy.int32(-1)

