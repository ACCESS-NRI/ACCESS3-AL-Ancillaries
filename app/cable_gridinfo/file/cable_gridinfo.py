#!/usr/bin/env python
"""
CABLE gridinfo generation
*************************
Combine the NetCDF ancillaries generated by the workflow into a CABLE gridinfo file:

- Soil properties come from the soil ancillary, converted to the gridinfo units.
- LAI is the regridded total (all plant functional types) LAI climatology.
- iveg/patchfrac are a compressed (non-zero tiles only) form of the land cover tile fractions.
- Fields which the workflow does not generate (e.g. Ndep, SoilTemp, isoil) are optionally
  sampled, using the nearest neighbour, from a reference gridinfo file.

"""
import argparse
from dataclasses import dataclass
from pathlib import Path
from typing import Callable, Optional

import ants
import ants.io.save as save
import ants.utils.cube
import iris
import iris.analysis
import iris.analysis.cartography
import iris.coords
import iris.cube
import numpy as np

WATER_DENSITY = 1000.0  # kg m-3

FLOAT_FILL_VALUE = np.float32(-1.0)
AREA_FILL_VALUE = np.float32(-99.0)
INTEGER_FILL_VALUE = np.int32(-1)

LAND_MASK_STASH = "m01s00i030"
LAND_MASK_VARIABLE = "land_binary_mask"
LAI_VARIABLE = "leaf_area_index"

# Variables which only the reference gridinfo can provide, with their non-spatial dimensions
REFERENCE_VARIABLES = {
    "Albedo": ("rad",),
    "Ndep": (),
    "Nfix": (),
    "Pdust": (),
    "Pwea": (),
    "SnowDepth": ("time",),
    "SoilMoist": ("time", "soil"),
    "SoilTemp": ("time", "soil"),
    "SoilOrder": (),
    "isoil": (),
}


# CF (udunits) units for reference variables whose units are missing, not parseable or not in the
# canonical form in the reference (Albedo is dimensionless, despite being labelled "m" there)
REFERENCE_UNITS_OVERRIDES = {
    "Albedo": "1",
    "SoilMoist": "m3 m-3",
    "SoilOrder": "1",
    "isoil": "1",
    "Ndep": "g m-2 year-1",
    "Nfix": "g m-2 year-1",
    "Pdust": "g m-2 year-1",
    "Pwea": "g m-2 year-1",
}


@dataclass(frozen=True)
class SoilFieldSpec:
    """A 2D (latitude, longitude) gridinfo variable taken from one field of the soil ancillary.

    `conversion` receives the source array and the dictionary of all soil arrays (keyed by
    STASH code), so derived quantities can use other fields.
    """

    target_name: str
    stash: str
    units: str
    long_name: str
    conversion: Callable[[np.ndarray, dict], np.ndarray] = lambda values, all_values: values


BULK_DENSITY_STASH = "m01s00i008"


def _saturated_conductivity_to_metres_per_second(values: np.ndarray, all_values: dict) -> np.ndarray:
    # kg m-2 s-1 of water -> m s-1
    return values / WATER_DENSITY


def _heat_capacity_per_mass(values: np.ndarray, all_values: dict) -> np.ndarray:
    # J m-3 K-1 -> J kg-1 K-1 by dividing by the bulk density; undefined (NaN) where density is zero
    bulk_density = all_values[BULK_DENSITY_STASH]
    with np.errstate(divide="ignore", invalid="ignore"):
        return np.where(bulk_density > 0.0, values / bulk_density, np.nan)


SOIL_FIELD_SPECS = (
    SoilFieldSpec("bch", "m01s00i207", "1", "CLAPP-HORNBERGER B COEFFICIENT"),
    SoilFieldSpec("ssat", "m01s00i043", "m3 m-3", "VOL SMC AT SATURATION"),
    SoilFieldSpec("sfc", "m01s00i041", "m3 m-3", "VOL SMC AT CRIT PT"),
    SoilFieldSpec("swilt", "m01s00i040", "m3 m-3", "VOL SMC AT WILTING"),
    SoilFieldSpec("sucs", "m01s00i048", "m", "SATURATED SOIL WATER SUCTION"),
    SoilFieldSpec(
        "hyds", "m01s00i044", "m s-1", "SAT SOIL CONDUCTIVITY", _saturated_conductivity_to_metres_per_second
    ),
    SoilFieldSpec("rhosoil", BULK_DENSITY_STASH, "kg m-3", "SOIL BULK DENSITY"),
    SoilFieldSpec("css", "m01s00i046", "J kg-1 K-1", "Soil specific heat capacity", _heat_capacity_per_mass),
    SoilFieldSpec("cnsd", "m01s00i047", "W m-1 K-1", "THERMAL CONDUCTIVITY"),
    SoilFieldSpec("sand", "m01s00i420", "1", "soil texture - sand fraction"),
    SoilFieldSpec("silt", "m01s00i419", "1", "soil texture - silt fraction"),
    SoilFieldSpec("clay", "m01s00i418", "1", "soil texture - clay fraction"),
    SoilFieldSpec("albedo2", "m01s00i220", "1", "SNOW-FREE ALBEDO OF SOIL"),
)

SOIL_STASH_CODES = {spec.stash for spec in SOIL_FIELD_SPECS}


# ----------------------------------------------------------------------------------------------
# Loading
# ----------------------------------------------------------------------------------------------
def masked_values_as_float(cube: iris.cube.Cube) -> np.ndarray:
    """Cube data as a float64 ndarray with masked points replaced by NaN."""
    return np.ma.filled(np.ma.asarray(cube.data, dtype=np.float64), np.nan)


def load_soil_values(soil_path: Path) -> dict:
    """The soil ancillary fields needed by SOIL_FIELD_SPECS, as arrays keyed by STASH code."""
    return {
        stash: masked_values_as_float(
            ants.io.load.load_cube(str(soil_path), iris.AttributeConstraint(STASH=stash))
        )
        for stash in SOIL_STASH_CODES
    }


def load_land_mask(land_mask_path: Path) -> iris.cube.Cube:
    """The land mask, which defines the grid; horizontal bounds are guessed if missing."""
    land_mask = ants.io.load.load_cube(str(land_mask_path), LAND_MASK_VARIABLE)
    ants.utils.cube.guess_horizontal_bounds(land_mask)
    return land_mask


# ----------------------------------------------------------------------------------------------
# Pure computation
# ----------------------------------------------------------------------------------------------
def compute_cell_area(land_mask: iris.cube.Cube) -> np.ndarray:
    """Area in m^2 of every cell of the (bounded) grid of the cube, shape (latitude, longitude)."""
    return iris.analysis.cartography.area_weights(land_mask, normalize=False)


def compress_tiles(tile_fractions: np.ndarray, tile_numbers: np.ndarray) -> tuple:
    """Compress full tile fractions (tile, lat, lon) to the non-zero tiles per cell.

    Returns (tile_number_per_patch, fraction_per_patch), each (patch, lat, lon), where the patch
    dimension is the largest number of non-zero tiles in any cell. Within a cell, patches are
    ordered by descending fraction. Unused patch slots hold the fill values.
    """
    safe_fractions = np.nan_to_num(tile_fractions, nan=0.0)
    patch_count = max(int((safe_fractions > 0.0).sum(axis=0).max()), 1)
    descending_order = np.argsort(-safe_fractions, axis=0, kind="stable")[:patch_count]
    ordered_fractions = np.take_along_axis(safe_fractions, descending_order, axis=0)
    ordered_tile_numbers = tile_numbers[descending_order]
    is_used = ordered_fractions > 0.0
    return (
        np.where(is_used, ordered_tile_numbers, INTEGER_FILL_VALUE).astype(np.int32),
        np.where(is_used, ordered_fractions, FLOAT_FILL_VALUE).astype(np.float32),
    )


def mask_outside_land(values: np.ndarray, is_land: np.ndarray) -> np.ma.MaskedArray:
    """Mask non-land points, and any non-finite land points.

    `is_land` is broadcast against the trailing (latitude, longitude) dimensions of `values`.
    """
    return np.ma.masked_where(~(is_land & np.isfinite(values)), values)


# ----------------------------------------------------------------------------------------------
# Building the gridinfo cubes
# ----------------------------------------------------------------------------------------------
def make_index_coordinate(dimension_name: str, size: int) -> iris.coords.DimCoord:
    """Coordinate numbering a non-spatial dimension, so the dimension is named in the output."""
    return iris.coords.DimCoord(
        np.arange(size, dtype=np.int32), long_name=dimension_name, var_name=dimension_name, units="1"
    )


def make_horizontal_coordinates(land_mask: iris.cube.Cube) -> tuple:
    """Unbounded latitude and longitude coordinates, without a coordinate system."""
    coordinates = []
    for coordinate_name in ("latitude", "longitude"):
        coordinate = land_mask.coord(coordinate_name).copy()
        coordinate.bounds = None
        coordinate.coord_system = None
        coordinate.points = coordinate.points.astype(np.float32)
        coordinates.append(coordinate)
    return tuple(coordinates)


def make_gridinfo_cube(
    name: str,
    values: np.ma.MaskedArray,
    leading_dimensions: tuple,
    horizontal_coordinates: tuple,
    attributes: dict,
    fill_value,
) -> iris.cube.Cube:
    """A cube with dimensions (*leading_dimensions, latitude, longitude).

    Units are CF compliant (udunits) strings, e.g. "m3 m-3".
    """
    leading_coordinates = [make_index_coordinate(dimension, size) for dimension, size in zip(leading_dimensions, values.shape)]
    coordinates = [*leading_coordinates, *horizontal_coordinates]
    cube = iris.cube.Cube(
        np.ma.array(np.ma.filled(values, fill_value).astype(type(fill_value)), mask=np.ma.getmaskarray(values)),
        var_name=name,
        long_name=attributes.get("long_name"),
        units=attributes.get("units", "1"),
        dim_coords_and_dims=[(coordinate, dimension) for dimension, coordinate in enumerate(coordinates)],
        attributes={"missing_value": fill_value},
    )
    return cube


def build_area_cube(land_mask: iris.cube.Cube, is_land: np.ndarray, horizontal_coordinates: tuple) -> iris.cube.Cube:
    return make_gridinfo_cube(
        "area",
        mask_outside_land(compute_cell_area(land_mask), is_land),
        (),
        horizontal_coordinates,
        {"units": "m2", "long_name": "grid cell area"},
        AREA_FILL_VALUE,
    )


def build_soil_cubes(soil_values: dict, is_land: np.ndarray, horizontal_coordinates: tuple) -> list:
    return [
        make_gridinfo_cube(
            spec.target_name,
            mask_outside_land(spec.conversion(soil_values[spec.stash], soil_values), is_land),
            (),
            horizontal_coordinates,
            {"units": spec.units, "long_name": spec.long_name},
            FLOAT_FILL_VALUE,
        )
        for spec in SOIL_FIELD_SPECS
    ]


def build_vegetation_cubes(vegetation_fraction_path: Path, is_land: np.ndarray, horizontal_coordinates: tuple) -> list:
    tile_cube = ants.io.load.load_cube(str(vegetation_fraction_path))
    tile_numbers = tile_cube.coord("pseudo_level").points
    patch_tile_numbers, patch_fractions = compress_tiles(
        np.where(is_land, masked_values_as_float(tile_cube), 0.0), tile_numbers
    )
    return [
        make_gridinfo_cube(
            "iveg",
            np.ma.masked_equal(patch_tile_numbers, INTEGER_FILL_VALUE),
            ("patch",),
            horizontal_coordinates,
            {"long_name": "CSIRO classification of veg type (tile number of each patch)"},
            INTEGER_FILL_VALUE,
        ),
        make_gridinfo_cube(
            "patchfrac",
            np.ma.masked_equal(patch_fractions, FLOAT_FILL_VALUE),
            ("patch",),
            horizontal_coordinates,
            {"long_name": "Patch fraction; non-zero vegetation tile fractions, largest first"},
            FLOAT_FILL_VALUE,
        ),
    ]


def build_lai_cube(lai_path: Path, is_land: np.ndarray, horizontal_coordinates: tuple) -> iris.cube.Cube:
    lai_cube = ants.io.load.load_cube(str(lai_path), LAI_VARIABLE)
    return make_gridinfo_cube(
        "LAI",
        mask_outside_land(masked_values_as_float(lai_cube), is_land),
        ("time",),
        horizontal_coordinates,
        {"units": "m2 m-2", "long_name": "leaf area index"},
        FLOAT_FILL_VALUE,
    )


def build_reference_cubes(
    reference_path: Path,
    land_mask: iris.cube.Cube,
    is_land: np.ndarray,
    horizontal_coordinates: tuple,
    excluded_names,
) -> list:
    """Sample the REFERENCE_VARIABLES present in a reference gridinfo onto the target grid.

    Sampling is nearest neighbour in latitude/longitude. Dimensions other than latitude and
    longitude (time, soil, rad) are kept as they are in the reference.
    """
    target_grid = land_mask.copy()
    reference_cubes = {cube.var_name: cube for cube in ants.io.load.load(str(reference_path))}
    sampled_cubes = []
    for name, leading_dimensions in REFERENCE_VARIABLES.items():
        if name in excluded_names or name not in reference_cubes:
            continue
        reference_cube = reference_cubes[name]
        for coordinate_name in ("latitude", "longitude"):
            reference_cube.coord(coordinate_name).coord_system = target_grid.coord(coordinate_name).coord_system
        sampled = reference_cube.regrid(target_grid, iris.analysis.Nearest())
        is_integer = np.issubdtype(reference_cube.dtype, np.integer)
        fill_value = INTEGER_FILL_VALUE if is_integer else (AREA_FILL_VALUE if name in ("Ndep", "Nfix", "Pdust", "Pwea") else FLOAT_FILL_VALUE)
        sampled_cubes.append(
            make_gridinfo_cube(
                name,
                mask_outside_land(masked_values_as_float(sampled), is_land),
                leading_dimensions,
                horizontal_coordinates,
                {"units": REFERENCE_UNITS_OVERRIDES.get(name, reference_cube.units), "long_name": reference_cube.long_name},
                fill_value,
            )
        )
    return sampled_cubes


# ----------------------------------------------------------------------------------------------
# Main
# ----------------------------------------------------------------------------------------------
def main(
    soil_path: Path,
    vegetation_fraction_path: Path,
    lai_path: Path,
    land_mask_path: Path,
    output_path: Path,
    reference_path: Optional[Path],
) -> None:
    land_mask = load_land_mask(land_mask_path)
    is_land = land_mask.data.astype(bool)  # (latitude, longitude)
    horizontal_coordinates = make_horizontal_coordinates(land_mask)

    cubes = [
        build_area_cube(land_mask, is_land, horizontal_coordinates),
        *build_vegetation_cubes(vegetation_fraction_path, is_land, horizontal_coordinates),
        build_lai_cube(lai_path, is_land, horizontal_coordinates),
        *build_soil_cubes(load_soil_values(soil_path), is_land, horizontal_coordinates),
    ]

    reference_cubes = []
    if reference_path is not None:
        reference_cubes = build_reference_cubes(
            reference_path, land_mask, is_land, horizontal_coordinates, {cube.var_name for cube in cubes}
        )
        cubes.extend(reference_cubes)

    omitted = [name for name in REFERENCE_VARIABLES if name not in {cube.var_name for cube in cubes}]
    if omitted:
        print(f"Not generated by the workflow and not in a reference gridinfo, omitted: {', '.join(omitted)}")

    save.netcdf(
        iris.cube.CubeList(cubes),
        str(output_path),
        netcdf_format="NETCDF4",
        local_keys=["missing_value"],
        zlib=True,
        fill_value=[cube.attributes["missing_value"] for cube in cubes],
    )


def _parse_args():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--soil", type=Path, required=True, help="Soil ancillary (NetCDF).")
    parser.add_argument("--vegetation-fraction", type=Path, required=True, help="Land cover tile fraction ancillary (NetCDF).")
    parser.add_argument("--lai", type=Path, required=True, help="Regridded total LAI climatology (NetCDF).")
    parser.add_argument("--land-mask", type=Path, required=True, help="Land mask ancillary (NetCDF) defining the grid.")
    parser.add_argument("--output", type=Path, required=True, help="Gridinfo file to write.")
    parser.add_argument(
        "--reference-gridinfo",
        type=lambda path: Path(path) if path else None,  # rose passes an empty string when unset
        default=None,
        help="Optional gridinfo providing the variables the workflow does not generate.",
    )
    return parser.parse_args()


if __name__ == "__main__":
    arguments = _parse_args()
    main(
        arguments.soil,
        arguments.vegetation_fraction,
        arguments.lai,
        arguments.land_mask,
        arguments.output,
        arguments.reference_gridinfo,
    )
